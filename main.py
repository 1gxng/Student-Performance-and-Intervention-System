# Intervention List
def view_intervention_list(valid_students):
    """Identify and display students requiring intervention."""
    print("\n--- Intervention List ---")

     # Initialize flag to track if any student needs intervention
    intervention_found = False

    # Iterate through each student record to evaluate intervention criteria
    for student in valid_students:
        # List to hold the explanation why the the student needss intervention
        reasons = []

        # Check each intervention condition separately
        # Condition 1: final mark below 50
        if student["final_mark"] < 50:
            reasons.append("Final mark below 50")

        # Condition 2: attendance below 75%
        if student["attendance_pct"] < 75:
            reasons.append("Attendance below 75%")

        # Condition 3: project not submitted
        if student["submitted_project"] is False:
            reasons.append("Project not submitted")

        # Display the student if at least one reason exists
        if reasons: # Check if list is empty
            intervention_found = True

            # Print details of flagged students
            print(f"\nStudent ID: {student['student_id']}")
            print(f"Submitted Project: {student['submitted_project']}")
            print(f"Final mark: {student['final_mark']:.2f}")
            print(f"Attendance: {student['attendance_pct']}%")
            print("Intervention reasons:")

            for reason in reasons:
                print(f"- {reason}")

    # Fallback if no students were flagged
    if intervention_found == False:
        print("No students require intervention.")
        
