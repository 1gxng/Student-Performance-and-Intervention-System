# function for calculating class avergae
def calculate_class_statistics(valid_students):
  # Creating empty data structures for storung results
  final_marks = [ mark['final_mark'] for mark in grade_final_mark(valid_students)]
  class_average = None
  result = dict()

  #list of only the correct marks without blanks
  class_average = sum(final_marks) / len(final_marks)
  highest_final_mark = max(final_marks)
  lowest_final_mark = min(final_marks)

  result['class_average'] = round(class_average,2)
  result['student_marks'] = final_marks
  result['highest_final_mark'] = highest_final_mark
  result['lowest_final_mark'] = lowest_final_mark
  result['students'] = len(final_marks)

  # returning a dictionary of output
  return result

# function to claculate final marks from assignment , cat and exam marks
def calculate_final_mark(valid_students):
  final_marks = None # Creating empty variable to store final mark
  new_student_records = list() # Creating empty list to new student details
  # looping through student records calculating final marks
  for record in valid_students:
    final_mark = (record['assignment_mark']*0.2) + (record['cat_mark']*0.2) + (record['exam_mark']*0.6)
    final_mark = round(final_mark,2)
    record['final_mark'] = final_mark
    new_student_records.append(record)
  # returning the student records with added final marks
  return new_student_records

# function to grade a student marks
def grade_final_mark(valid_students):
  grade = None # Creating empty variable to store grades
  new_student_records = list() # Creating empty list to new student details
  valid_students = calculate_final_mark(valid_students)
   # looping through student records calculating grades
  for record in valid_students:
    final_mark = record['final_mark']
    if final_mark >=70: grade = "A"
    elif final_mark >=60: grade = "B"
    elif final_mark >=50: grade = "C"
    elif final_mark >=40: grade = "D"
    else: grade = "E"
    record['grade'] = grade
    new_student_records.append(record)
  # returning the student records with added grades
  return new_student_records

# function to count grades in class final marks
def count_students_in_every_grade(valid_students):
  grade_counts = {'A': 0, 'B': 0, 'C': 0, 'D': 0, 'E': 0, 'F': 0}
  valid_students = grade_final_mark(valid_students)
  for record in valid_students:
    grade = record['grade']
    grade_counts[grade] += 1

  return grade_counts

# function to display class perfomance
def display_perfomance(valid_students):
  stats = calculate_class_statistics(valid_students)
  grade_counts = count_students_in_every_grade(valid_students)
  print("\n--------------Class Perfomance Summary---------------")
  print(f"Class Average: {stats['class_average']} ")
  print(f"Highest Mark: {stats['highest_final_mark']}")
  print(f"Lowest Mark: {stats['lowest_final_mark']}")
  print(f"Total Students: {stats['students']}")
  print(f"Grades Summary: {grade_counts}")



